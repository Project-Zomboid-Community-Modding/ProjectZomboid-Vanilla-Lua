TopOfTheWorld.Add = function()
	addChallenge(TopOfTheWorld);
end

TopOfTheWorld.OnGameStart = function()
    if getPlayer():getHoursSurvived() > 0 then
        return
    end
    local sq = getSquare(12796, 1528, 0);
    local vehicle = getWorld():getRandomizedWorldBase():addVehicle(sq, nil, nil, "Base.PickUpVan", nil, nil, "Survivalist");
    vehicle:repair();
    vehicle:addKeyToGloveBox();
    vehicle:setLocked(false);
end

